import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname),'..');
const read = file => fs.readFileSync(path.join(root,file),'utf8');
const ini = read('Clash/config/ZJU.ini');
const core = read('Clash/config/src/substore-core.js').replace('// @REGION_DEFINITIONS@',read('Clash/config/src/regions.js'));
const outputs = new Map();
for (const [suffix,target] of [['','ClashMeta'],['-surge','Surge']]) {
  outputs.set(`Clash/config/zju-sub-store${suffix}.js`,
    `// Generated by scripts/build_substore.mjs; edit ZJU.ini and config/src instead.\nconst $target = '${target}';\n`+core);
  outputs.set(`Clash/config/zju-sub-store-loader${suffix}.js`,
`// Stable loader: the INI and generator arrive together in one versioned payload.
const bundle = JSON.parse($content ?? $files?.[0]);
if (bundle.schema !== 1 || typeof bundle.ini !== 'string' || typeof bundle.core !== 'string') throw new Error('不支持的原子配置包；保留上次有效配置');
const AsyncFunction = Object.getPrototypeOf(async function(){}).constructor;
$content = await new AsyncFunction('$content','$files','produceArtifact','ProxyUtils','$arguments','$target',bundle.core+'\\nreturn $content;')(
  bundle.ini, [], produceArtifact, ProxyUtils, typeof $arguments === 'object' ? $arguments : {}, '${target}');
`);
}
outputs.set('Clash/config/substore-bundle.json',JSON.stringify({schema:1,ini,core},null,2)+'\n');
let stale = false;
for (const [file,content] of outputs) {
  const full = path.join(root,file);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(full) || read(file)!==content) {console.error('Stale generated file: '+file);stale=true;}
  } else fs.writeFileSync(full,content);
}
if (stale) process.exitCode=1;
else console.log(process.argv.includes('--check') ? 'Generated artifacts match their sources' : 'Built standalone scripts and atomic bundle');
